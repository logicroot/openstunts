const TrackObjectDef* track_objects() { return kTrackObjects; }

const TrackObjectDef& track_object(int index) {
  if (index < 0) index = 0;
  if (index >= kTrackObjectCount) index = kTrackObjectCount - 1;
  return kTrackObjects[index];
}

const TerrainShape* terrain_shapes() { return kTerrainShapes; }

const char* shape_name(int index) {
  if (index < 0 || static_cast<size_t>(index) >= ShapeLibrary::track_shape_count()) {
    return "";
  }
  return ShapeLibrary::track_shape_name(static_cast<size_t>(index));
}

bool track_object_at(const Track& track, int x, int y, PlacedTrackObject* out) {
  if (out == nullptr || x < 0 || y < 0 || x >= Track::kSize || y >= Track::kSize) {
    return false;
  }
  const int item = track.item(x, y);
  if (item == 0) return false;

  // Continuation markers name a neighbour cell (column/row offsets are relative
  // to the owner, which is one column left and/or one row below in our layout).
  int ox = x;
  int oy = y;
  if (item == kTileContinuationSoutheast) {  // owner: x-1, y+1
    ox = x - 1;
    oy = y + 1;
  } else if (item == kTileContinuationSouth) {  // owner: x, y+1
    oy = y + 1;
  } else if (item == kTileContinuationEast) {  // owner: x-1, y
    ox = x - 1;
  }
  if (ox < 0 || oy < 0 || ox >= Track::kSize || oy >= Track::kSize) return false;

  const int owner_item = track.item(ox, oy);
  if (owner_item == 0 || owner_item >= kTileContinuationSoutheast) return false;

  out->object = &track_object(owner_item);
  out->item = owner_item;
  out->owner_x = ox;
  out->owner_y = oy;
  return true;
}

